-- =============================================================
-- 0008_all_grade_types
--
-- Полный набор типов оценок (13 штук) с весами и цветами.
-- СТАРЫЕ ОЦЕНКИ СОХРАНЯЮТСЯ — они переносятся на новые типы
-- по смысловому соответствию:
--
--   старое имя                вес  →  новое имя                вес
--   Работа на уроке           1.0  →  Работа на уроке          1.0
--   Ответ на уроке            1.0  →  Работа на уроке          1.0
--   Домашнее задание          1.0  →  Домашнее задание         1.0
--   Самостоятельная работа    1.5  →  Самостоятельная работа   2.0
--   Контрольная работа        2.0  →  Контрольная работа       3.0
--   Проект                    1.5  →  Практическая работа      1.5
--
-- Всё, что не попало в таблицу выше (нестандартные типы),
-- мапится на «Работа на уроке» и попадает в NOTICE.
--
-- Новый полный список:
--   1.0 — Работа на уроке, Домашнее задание
--   1.5 — Лабораторная, Практическая, Тест, Словарный диктант,
--         Терминологический диктант, Проверка тетрадей
--   2.0 — Самостоятельная работа
--   2.5 — Сочинение, Изложение, Проверочная работа
--   3.0 — Контрольная работа
-- =============================================================

BEGIN;

-- ---------- 1. Вставляем новые типы ----------
INSERT INTO grade_types (name, weight, color) VALUES
    ('Работа на уроке',            1.0, '#94a3b8'),
    ('Домашнее задание',           1.0, '#a3a3a3'),

    ('Лабораторная работа',        1.5, '#22c55e'),
    ('Практическая работа',        1.5, '#16a34a'),
    ('Тест',                       1.5, '#65a30d'),
    ('Словарный диктант',          1.5, '#84cc16'),
    ('Терминологический диктант',  1.5, '#0d9488'),
    ('Проверка тетрадей',          1.5, '#14b8a6'),

    ('Самостоятельная работа',     2.0, '#0ea5e9'),

    ('Сочинение',                  2.5, '#8b5cf6'),
    ('Изложение',                  2.5, '#a855f7'),
    ('Проверочная работа',         2.5, '#d946ef'),

    ('Контрольная работа',         3.0, '#dc2626')
ON CONFLICT (name) DO UPDATE
    SET weight = EXCLUDED.weight,
        color  = EXCLUDED.color;

-- ---------- 2. Маппинг старых → новых ----------
-- Читаем пары (old_name, new_name) из временной таблицы.
CREATE TEMP TABLE grade_type_map (old_name TEXT, new_name TEXT) ON COMMIT DROP;
INSERT INTO grade_type_map VALUES
    ('Работа на уроке',        'Работа на уроке'),
    ('Ответ на уроке',         'Работа на уроке'),
    ('Домашнее задание',       'Домашнее задание'),
    ('Самостоятельная работа', 'Самостоятельная работа'),
    ('Контрольная работа',     'Контрольная работа'),
    ('Проект',                 'Практическая работа');

-- 2.1. Прямой маппинг по таблице
UPDATE grades g
SET grade_type_id = nt.id
FROM grade_types ot
JOIN grade_type_map m ON m.old_name = ot.name
JOIN grade_types nt ON nt.name = m.new_name
WHERE g.grade_type_id = ot.id
  AND ot.name <> m.new_name;

-- 2.2. Fallback: всё, чего нет в старом списке, но что ссылается
--      на тип, которого больше не должно быть, — на «Работу на уроке».
DO $$
DECLARE
    fallback_id INT;
    orphaned    INT;
BEGIN
    SELECT id INTO fallback_id FROM grade_types WHERE name = 'Работа на уроке';
    IF fallback_id IS NULL THEN
        RAISE EXCEPTION 'Не найден тип «Работа на уроке»';
    END IF;

    -- Считаем «осиротевшие» — те, что ссылаются на типы,
    -- которых нет среди новых 13.
    SELECT COUNT(*) INTO orphaned
    FROM grades g
    JOIN grade_types t ON t.id = g.grade_type_id
    WHERE t.name NOT IN (
        'Работа на уроке','Домашнее задание',
        'Лабораторная работа','Практическая работа','Тест',
        'Словарный диктант','Терминологический диктант','Проверка тетрадей',
        'Самостоятельная работа','Сочинение','Изложение','Проверочная работа',
        'Контрольная работа'
    );

    IF orphaned > 0 THEN
        RAISE NOTICE 'Мапим % оценок на «Работа на уроке» (нестандартные типы)', orphaned;

        UPDATE grades g
        SET grade_type_id = fallback_id
        FROM grade_types t
        WHERE g.grade_type_id = t.id
          AND t.name NOT IN (
            'Работа на уроке','Домашнее задание',
            'Лабораторная работа','Практическая работа','Тест',
            'Словарный диктант','Терминологический диктант','Проверка тетрадей',
            'Самостоятельная работа','Сочинение','Изложение','Проверочная работа',
            'Контрольная работа'
          );
    END IF;
END$$;

-- ---------- 3. Удаляем старые типы ----------
-- После маппинга на старые типы уже никто не ссылается.
DELETE FROM grade_types
WHERE name NOT IN (
    'Работа на уроке','Домашнее задание',
    'Лабораторная работа','Практическая работа','Тест',
    'Словарный диктант','Терминологический диктант','Проверка тетрадей',
    'Самостоятельная работа','Сочинение','Изложение','Проверочная работа',
    'Контрольная работа'
);

COMMIT;
