-- =============================================================
-- 0004_summer_before_year
-- Летние каникулы перед началом учебного года (июнь–август 2026).
-- =============================================================

INSERT INTO holidays (name, start_date, end_date)
SELECT 'Летние каникулы (перед учебным годом)', '2026-06-01', '2026-08-31'
WHERE NOT EXISTS (
    SELECT 1 FROM holidays
    WHERE name = 'Летние каникулы (перед учебным годом)'
);
