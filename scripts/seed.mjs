  const classIdByName = new Map(allClasses.map(c => [c.name, c.id]))

  const { rows: allSubjects } = await client.query(`SELECT id, name FROM subjects`)
  const subjectIdByName = new Map(allSubjects.map(s => [s.name, s.id]))

  let scheduleCount = 0
  for (const [className, day, lesson, subjectName, teacher] of SCHEDULE) {
    const classId = classIdByName.get(className)
    const subjectId = subjectIdByName.get(subjectName)
    if (!classId) { console.warn(`⚠ класс ${className} не найден — пропуск`); continue }
    if (!subjectId) { console.warn(`⚠ предмет ${subjectName} не найден — пропуск`); continue }

    await client.query(
      `INSERT INTO schedule (class_id, subject_id, teacher, day_of_week, lesson_num)
       VALUES ($1, $2, $3, $4, $5)`,
      [classId, subjectId, teacher, day, lesson]
    )
    scheduleCount++
  }
  console.log(`✓ Уроков в расписании: ${scheduleCount}`)

  await client.query('COMMIT')
  console.log('\n✅ Готово.')
